#!/usr/bin/env python3
"""Compile the CRT filter's shaders (src/app/gpu/crt.vert, crt.frag) and write
src/app/gpu/crt_gen.h, which is committed: a build needs no shader tools,
only changing a shader does.

  build_crt_shaders.py

glslang compiles the GLSL to SPIR-V (Vulkan); SPIRV-Cross turns the SPIR-V
into MSL (Metal). Both are tools only (Homebrew: glslang spirv-cross; Linux
distributions package both). There is no DXIL: on Direct3D 12 the filter is
unavailable and the launcher says so.
"""

import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "app", "gpu", "crt_gen.h")
WORK = os.path.join(ROOT, "build", "shaders")
SHADERS = [("crt_vs", "src/app/gpu/crt.vert"), ("crt_ps", "src/app/gpu/crt.frag")]


def main():
    glslang = shutil.which("glslangValidator") or shutil.which("glslang")
    spirv_cross = shutil.which("spirv-cross")
    if not glslang or not spirv_cross:
        sys.exit("build_crt_shaders: needs glslangValidator (glslang) and spirv-cross on PATH")
    os.makedirs(WORK, exist_ok=True)
    out = ["// Generated by scripts/build_crt_shaders.py from src/app/gpu/crt.vert and crt.frag: do not edit.",
           "#pragma once", ""]
    for name, src in SHADERS:
        spv = os.path.join(WORK, name + ".spv")
        metal = os.path.join(WORK, name + ".metal")
        subprocess.run([glslang, "-V", "--target-env", "vulkan1.0", "-o", spv, os.path.join(ROOT, src)], check=True)
        subprocess.run([spirv_cross, spv, "--msl", "--msl-version", "20100", "--output", metal], check=True)
        data = open(spv, "rb").read()
        rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
        out.append(f"static const unsigned char k_{name}_spv[] = {{\n    " + ",\n    ".join(rows) + "\n};\n")
        text = open(metal).read()
        body = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n\"\n    \"")
        out.append(f"static const char k_{name}_msl[] =\n    \"{body}\";\n")
    open(OUT, "w").write("\n".join(out))
    print(f"build_crt_shaders: wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
